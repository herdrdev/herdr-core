#!/bin/sh
# homebrew-formula.sh prints the Homebrew formula for one herdr-core release.
#
# Usage: distribution/homebrew-formula.sh VERSION MANIFEST_FILE
#
# VERSION is the release version without a leading "v" (for example 0.1.22).
# MANIFEST_FILE is the release's manifest.json produced by scripts/manifest.
# Fails closed, printing nothing to stdout, if VERSION disagrees with
# MANIFEST_FILE or any macOS/Linux target URL or SHA-256 is missing/invalid.
set -eu

if [ "$#" -ne 2 ]; then
	echo "usage: $0 VERSION MANIFEST_FILE" >&2
	exit 2
fi
version="$1"
manifest="$2"

if [ ! -f "$manifest" ]; then
	echo "error: manifest file not found: $manifest" >&2
	exit 1
fi

flat="$(tr -d '\n\r\t ' < "$manifest")"
manifest_version="$(printf '%s' "$flat" | sed -n 's/.*"version":"\([^"]*\)".*/\1/p')"
if [ "$manifest_version" != "$version" ]; then
	echo "error: manifest version '$manifest_version' does not match requested version '$version'" >&2
	exit 1
fi

extract_field() {
	target="$1"
	field="$2"
	entry="$(printf '%s' "$flat" | sed -n "s/.*\"${target}\":{\([^}]*\)}.*/\1/p")"
	if [ -z "$entry" ]; then
		echo "error: target ${target} is missing from $manifest" >&2
		exit 1
	fi
	val="$(printf '%s' "$entry" | sed -n "s/.*\"${field}\":\"\([^\"]*\)\".*/\1/p")"
	if [ -z "$val" ]; then
		echo "error: ${field} for ${target} is missing from $manifest" >&2
		exit 1
	fi
	if [ "$field" = "sha256" ]; then
		printf '%s\n' "$val" | grep -Eq '^[0-9a-fA-F]{64}$' || {
			echo "error: invalid sha256 for ${target} in $manifest" >&2
			exit 1
		}
	fi
	printf '%s\n' "$val"
}

macos_arm_url="$(extract_field macos-aarch64 url)"
macos_arm_sha="$(extract_field macos-aarch64 sha256)"
macos_x64_url="$(extract_field macos-x86_64 url)"
macos_x64_sha="$(extract_field macos-x86_64 sha256)"
linux_arm_url="$(extract_field linux-aarch64 url)"
linux_arm_sha="$(extract_field linux-aarch64 sha256)"
linux_x64_url="$(extract_field linux-x86_64 url)"
linux_x64_sha="$(extract_field linux-x86_64 sha256)"

cat <<EOF
# Formula/herdr-core.rb is generated by distribution/homebrew-formula.sh.
# Do not edit it by hand.
class HerdrCore < Formula
  desc "Terminal runtime for coding agents"
  homepage "https://github.com/herdrdev/herdr-core"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${macos_arm_url}"
      sha256 "${macos_arm_sha}"
    end
    on_intel do
      url "${macos_x64_url}"
      sha256 "${macos_x64_sha}"
    end
  end

  on_linux do
    on_arm do
      url "${linux_arm_url}"
      sha256 "${linux_arm_sha}"
    end
    on_intel do
      url "${linux_x64_url}"
      sha256 "${linux_x64_sha}"
    end
  end

  def install
    bin.install "herdr-core"
    bin.install_symlink "herdr-core" => "hc"
    prefix.install "THIRD-PARTY-NOTICES" if File.exist?("THIRD-PARTY-NOTICES")
  end

  test do
    assert_match "hc #{version}", shell_output("#{bin}/hc --version")
  end
end
EOF
