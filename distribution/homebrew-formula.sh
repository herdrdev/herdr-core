#!/usr/bin/env python3
# homebrew-formula.sh prints the Homebrew formula for one herdr-core release.
#
# Usage: distribution/homebrew-formula.sh VERSION MANIFEST_FILE
#
# VERSION is the release version without a leading "v" (for example 0.1.22).
# MANIFEST_FILE is the release's manifest.json produced by scripts/manifest.
# Fails closed, printing nothing to stdout, when VERSION disagrees with
# MANIFEST_FILE or any macOS/Linux target URL or SHA-256 is missing or invalid.
import json
import pathlib
import re
import sys
import urllib.parse

VERSION_RE = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?$")
SHA256_RE = re.compile(r"^[0-9a-fA-F]{64}$")
REQUIRED_TARGETS = ("macos-aarch64", "macos-x86_64", "linux-aarch64", "linux-x86_64")


def fail(message: str, code: int = 1) -> "None":
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(code)


def ruby_string(value: str) -> str:
    # Escape backslashes, double quotes, and '#' so Ruby string interpolation
    # (#{...}) can never trigger inside a double-quoted formula literal.
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("#", "\\#")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )
    return f'"{escaped}"'


def validate_url(target: str, raw: object) -> str:
    if not isinstance(raw, str) or not raw:
        fail(f"url for {target} is missing or not a string")
    if any(ch.isspace() or ord(ch) < 0x20 or ord(ch) == 0x7F for ch in raw):
        fail(f"url for {target} contains control characters or whitespace")
    parsed = urllib.parse.urlsplit(raw)
    try:
        port = parsed.port
    except ValueError:
        fail(f"url for {target} has an invalid port: {raw!r}")
    if parsed.scheme != "https" or not parsed.hostname or not parsed.path.startswith("/"):
        fail(f"url for {target} must be an https:// URL with hostname and path: {raw!r}")
    if port is not None and not (1 <= port <= 65535):
        fail(f"url for {target} has an out-of-range port: {raw!r}")
    if parsed.username or parsed.password or parsed.fragment:
        fail(f"url for {target} must not contain credentials or fragments: {raw!r}")
    return raw


def validate_sha256(target: str, raw: object) -> str:
    if not isinstance(raw, str) or not SHA256_RE.match(raw):
        fail(f"invalid sha256 for {target}: {raw!r}")
    return raw.lower()


def main() -> None:
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} VERSION MANIFEST_FILE", file=sys.stderr)
        raise SystemExit(2)

    version = sys.argv[1]
    manifest_path = pathlib.Path(sys.argv[2])
    if not VERSION_RE.match(version):
        fail(f"invalid release version: {version!r}")
    if not manifest_path.is_file():
        fail(f"manifest file not found: {manifest_path}")

    try:
        doc = json.loads(manifest_path.read_text(encoding="utf-8"))
    except Exception as exc:
        fail(f"invalid JSON in {manifest_path}: {exc}")

    if not isinstance(doc, dict):
        fail(f"manifest root in {manifest_path} must be an object")
    manifest_version = doc.get("version")
    if manifest_version != version:
        fail(f"manifest version {manifest_version!r} does not match requested version {version!r}")

    targets = doc.get("targets")
    if not isinstance(targets, dict):
        fail(f"manifest targets in {manifest_path} must be an object")

    resolved: dict[str, tuple[str, str]] = {}
    for target in REQUIRED_TARGETS:
        entry = targets.get(target)
        if not isinstance(entry, dict):
            fail(f"target {target} is missing from {manifest_path}")
        resolved[target] = (
            validate_url(target, entry.get("url")),
            validate_sha256(target, entry.get("sha256")),
        )

    macos_arm_url, macos_arm_sha = resolved["macos-aarch64"]
    macos_x64_url, macos_x64_sha = resolved["macos-x86_64"]
    linux_arm_url, linux_arm_sha = resolved["linux-aarch64"]
    linux_x64_url, linux_x64_sha = resolved["linux-x86_64"]

    formula = f"""# Formula/herdr-core.rb is generated by distribution/homebrew-formula.sh.
# Do not edit it by hand.
class HerdrCore < Formula
  desc "Terminal runtime for coding agents"
  homepage "https://github.com/herdrdev/herdr-core"
  version {ruby_string(version)}
  license "Apache-2.0"

  on_macos do
    on_arm do
      url {ruby_string(macos_arm_url)}
      sha256 {ruby_string(macos_arm_sha)}
    end
    on_intel do
      url {ruby_string(macos_x64_url)}
      sha256 {ruby_string(macos_x64_sha)}
    end
  end

  on_linux do
    on_arm do
      url {ruby_string(linux_arm_url)}
      sha256 {ruby_string(linux_arm_sha)}
    end
    on_intel do
      url {ruby_string(linux_x64_url)}
      sha256 {ruby_string(linux_x64_sha)}
    end
  end

  def install
    bin.install "herdr-core"
    bin.install_symlink "herdr-core" => "hc"
    prefix.install "THIRD-PARTY-NOTICES" if File.exist?("THIRD-PARTY-NOTICES")
  end

  test do
    assert_match "hc #{{version}}", shell_output("#{{bin}}/hc --version")
  end
end"""
    print(formula)


if __name__ == "__main__":
    main()
